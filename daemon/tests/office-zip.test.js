test("office ZIP: rejects unsafe portable paths on export and import", () => {
  const names = ["../escape", "a/../../escape", "/absolute", "C:/absolute", "C:relative", "//server/share", "\\server\\share", "a\\..\\escape", "a//b", "./a", "a/./b", "a/../b", "a\0b", "a\nb", "foo:ads", "dir/CON.txt", "NUL", "a/COM1.md", "LPT9", "COM¹.log", "CONIN$", "CONOUT$.log", "con .txt", "a.", "a ", "a/b. /c", "a?b", "a*b", 'a"b', "a<b", "a|b"];
  for (const name of names) {
    assert.throws(() => zip.encode([{ name, data: "x" }]), /entry path/, name);
    assert.throws(() => zip.decode(fixture(name)), /entry path/, name);
  }
  assert.throws(() => zip.decode(fixture("")), /entry path/);
  assert.throws(() => zip.encode([{ name: "bad\ud800.md", data: "x" }]), /filename/);
  assert.throws(() => zip.decode(fixture(Buffer.from([0xff]))), /UTF-8/);
});

test("office ZIP: prevents case/Unicode duplicates and file-directory collisions", () => {
  for (const names of [["a.md", "A.md"], ["é.md", "e\u0301.md"], ["a", "a/"], ["dir/file.md", "DIR"], ["a", "a/b"]]) {
    assert.throws(() => zip.encode(names.map((name) => ({ name, data: "" }))), /duplicate|parent directory/);
    assert.throws(() => zip.decode(combine(names.map((name) => fixture(name, Buffer.alloc(0))))), /duplicate|parent directory/);
  }
  assert.equal(zip.decode(combine([fixture("dir/", Buffer.alloc(0)), fixture("dir/a", Buffer.from("x"))])).length, 1);
});

test("office ZIP: rejects symlinks, devices, and inconsistent directory attributes", () => {
  for (const attrs of [0xa1ff0000, 0x21ff0000, 0x61ff0000, 0x11ff0000, 8, 0x10, 0x41ed0000]) {
    assert.throws(() => zip.decode(fixture("file", Buffer.from("x"), { attrs })), /nonregular|directory attributes/);
  }
  assert.throws(() => zip.decode(fixture("dir/", Buffer.alloc(0), { attrs: 0x81a40000 })), /file attributes/);
  assert.throws(() => zip.decode(fixture("dir/", Buffer.from("x"))), /directory entry has data/);
  assert.throws(() => zip.encode([{ name: "dir/", data: "x" }]), /directory entry has data/);
});

test("office ZIP: validates local/central filenames, flags, methods, sizes, and CRC", () => {
  for (const [offset, value] of [[4, 10], [6, 0], [8, 8], [14, 0], [18, 0], [22, 0]]) {
    const archive = zip.encode([{ name: "file.md", data: "data" }]);
    if (offset < 14) archive.writeUInt16LE(value, offset); else archive.writeUInt32LE(value, offset);
    assert.throws(() => zip.decode(archive), /metadata mismatch|size or checksum mismatch/);
  }
  const badName = zip.encode([{ name: "file.md", data: "data" }]);
  badName[30] = 0x78;
  assert.throws(() => zip.decode(badName), /filename mismatch/);
  const badPayload = zip.encode([{ name: "file.md", data: "data" }]);
  badPayload[37] ^= 1;
  assert.throws(() => zip.decode(badPayload), /checksum mismatch/);
  const badDescriptor = fixture("file.md", Buffer.from("data"), { descriptor: true });
  badDescriptor[centralOffset(badDescriptor) - 1] ^= 1;
  assert.throws(() => zip.decode(badDescriptor), /data descriptor/);
});

test("office ZIP: rejects unsupported flags, compression, ZIP64 and multidisk records", () => {
  for (const flag of [1, 0x10, 0x20, 0x40, 0x2000, 0x4000]) assert.throws(() => zip.decode(fixture("a", Buffer.from("x"), { flags: 0x800 | flag })), /flags/);
  assert.throws(() => zip.decode(fixture("a", Buffer.from("x"), { method: 99 })), /compression/);
  assert.throws(() => zip.decode(fixture("a", Buffer.from("x"), { method: 0, flags: 0x802 })), /flags/);
  for (const [target, field, value, width] of [["end", 4, 1, 2], ["end", 6, 1, 2], ["end", 8, 2, 2], ["end", 10, 0xffff, 2], ["end", 12, 0xffffffff, 4], ["central", 6, 45, 2], ["central", 20, 0xffffffff, 4], ["central", 34, 1, 2], ["central", 42, 0xffffffff, 4]]) {
    const archive = fixture("a");
    const offset = target === "end" ? endOffset(archive) : centralOffset(archive);
    if (width === 2) archive.writeUInt16LE(value, offset + field); else archive.writeUInt32LE(value, offset + field);
    assert.throws(() => zip.decode(archive), /ZIP64|multidisk/);
  }
});

test("office ZIP: validates local and central extra fields without accepting ZIP64", () => {
  for (const where of ["local", "central"]) {
    assert.throws(() => zip.decode(withExtra(fixture("a"), Buffer.from([1, 0, 0, 0]), where)), /ZIP64/);
    assert.throws(() => zip.decode(withExtra(fixture("a"), Buffer.from([0xfe, 0xca, 1, 0]), where)), /bounds/);
    assert.throws(() => zip.decode(withExtra(fixture("a"), Buffer.from([0xfe, 0xca, 0]), where)), /bounds/);
    assert.equal(zip.decode(withExtra(fixture("a"), Buffer.from([0xfe, 0xca, 0, 0]), where))[0].data.toString(), "payload");
  }
});

test("office ZIP: rejects truncated records, offsets, hidden data, and overlapping local entries", () => {
  const archive = fixture("file.md");
  for (const cut of [0, 1, 5, 21, archive.length - 1]) assert.throws(() => zip.decode(archive.subarray(0, cut)), /ZIP/);
  const offset = Buffer.from(archive);
  offset.writeUInt32LE(0xfffffff0, centralOffset(offset) + 42);
  assert.throws(() => zip.decode(offset), /bounds/);
  const hugeName = Buffer.from(archive);
  hugeName.writeUInt16LE(0xffff, centralOffset(hugeName) + 28);
  assert.throws(() => zip.decode(hugeName), /bounds/);
  const hugeCentral = Buffer.from(archive);
  hugeCentral.writeUInt32LE(0x7fffffff, endOffset(hugeCentral) + 12);
  assert.throws(() => zip.decode(hugeCentral), /bounds/);
  const withPrefix = Buffer.concat([Buffer.from("extra"), archive]);
  withPrefix.writeUInt32LE(centralOffset(archive) + 5, endOffset(withPrefix) + 16);
  withPrefix.writeUInt32LE(5, centralOffset(withPrefix) + 42);
  assert.throws(() => zip.decode(withPrefix), /unexpected data/);
  // Two central records alias one local record with different Unicode spellings.
  const overlap = combine([fixture("a"), fixture("b")]);
  overlap.writeUInt32LE(0, centralOffset(overlap) + 47 + 42);
  assert.throws(() => zip.decode(overlap), /filename mismatch|overlapping/);
});

test("office ZIP: bounds archive, entry count, uncompressed sizes, and deflate expansion", () => {
  assert.throws(() => zip.decode(Buffer.alloc(zip.MAX_ARCHIVE_BYTES + 1)), /archive exceeds/);
  assert.throws(() => zip.encode([{ name: "a", data: Buffer.alloc(zip.MAX_ENTRY_BYTES + 1) }]), /entry exceeds/);
  assert.throws(() => zip.encode(Array.from({ length: zip.MAX_ENTRIES + 1 }, (_, n) => ({ name: String(n), data: "" }))), /too many/);
  const count = fixture("a");
  count.writeUInt16LE(zip.MAX_ENTRIES + 1, endOffset(count) + 8);
  count.writeUInt16LE(zip.MAX_ENTRIES + 1, endOffset(count) + 10);
  assert.throws(() => zip.decode(count), /too many/);
  const data = Buffer.alloc(zip.MAX_ENTRY_BYTES, 65);
  assert.throws(() => zip.encode(Array.from({ length: 3 }, (_, n) => ({ name: String(n), data }))), /archive exceeds/);
  assert.throws(() => zip.encode(Array.from({ length: 9 }, (_, n) => ({ name: String(n), data }))), /total uncompressed/);
  assert.equal(zip.decode(fixture("at-limit", data))[0].data.length, zip.MAX_ENTRY_BYTES);
  assert.throws(() => zip.decode(fixture("large", Buffer.from("x"), { size: zip.MAX_ENTRY_BYTES + 1 })), /entry exceeds/);
  const tiny = fixture("bomb", data, { size: 1 });
  assert.ok(tiny.length < 10000);
  assert.throws(() => zip.decode(tiny), /oversized deflate/);
  // Declared aggregate size is rejected before any payload is inflated.
  const tooManyBytes = combine(Array.from({ length: 9 }, (_, n) => fixture(String(n), Buffer.from("x"), { size: zip.MAX_ENTRY_BYTES })));
  assert.throws(() => zip.decode(tooManyBytes), /total uncompressed/);
  assert.throws(() => zip.decode(fixture("bad", Buffer.from("x"), { packed: Buffer.from([0xff, 0xff]) })), /deflate/);
  assert.throws(() => zip.decode(fixture("tail", Buffer.from("x"), { packed: Buffer.concat([deflateRawSync(Buffer.from("x")), Buffer.from("extra")]) })), /trailing compressed/);
  assert.throws(() => zip.decode(fixture("short", Buffer.from("x"), { size: 2 })), /uncompressed size mismatch/);
});
