"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { deflateRawSync } = require("node:zlib");
const zip = require("../office-zip");

const endOffset = (buffer) => buffer.length - 22;
const centralOffset = (buffer) => buffer.readUInt32LE(endOffset(buffer) + 16);
function checksum(data) {
  let crc = 0xffffffff;
  for (const value of data) {
    crc ^= value;
    for (let bit = 0; bit < 8; bit++) crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1;
  }
  return (crc ^ 0xffffffff) >>> 0;
}

// Independent one-entry writer for archives our exporter does not produce,
// including stream descriptors, hostile names, and forged size declarations.
function fixture(name, data = Buffer.from("payload"), options = {}) {
  const nameBytes = Buffer.isBuffer(name) ? name : Buffer.from(name);
  const method = options.method ?? 8;
  const packed = options.packed || (method === 8 ? deflateRawSync(data) : data);
  const flags = options.flags ?? (0x800 | (options.descriptor ? 8 : 0));
  const size = options.size ?? data.length, crc = checksum(data);
  const local = Buffer.alloc(30), central = Buffer.alloc(46), end = Buffer.alloc(22);
  local.writeUInt32LE(0x04034b50, 0);
  local.writeUInt16LE(20, 4);
  local.writeUInt16LE(flags, 6);
  local.writeUInt16LE(method, 8);
  if (!options.descriptor || options.localSizes) {
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(packed.length, 18);
    local.writeUInt32LE(size, 22);
  }
  local.writeUInt16LE(nameBytes.length, 26);
  let descriptor = Buffer.alloc(0);
  if (options.descriptor) {
    const start = options.signature === false ? 0 : 4;
    descriptor = Buffer.alloc(start + 12);
    if (start) descriptor.writeUInt32LE(0x08074b50, 0);
    descriptor.writeUInt32LE(crc, start);
    descriptor.writeUInt32LE(packed.length, start + 4);
    descriptor.writeUInt32LE(size, start + 8);
  }
  central.writeUInt32LE(0x02014b50, 0);
  central.writeUInt16LE(0x0314, 4);
  central.writeUInt16LE(20, 6);
  central.writeUInt16LE(flags, 8);
  central.writeUInt16LE(method, 10);
  central.writeUInt32LE(crc, 16);
  central.writeUInt32LE(packed.length, 20);
  central.writeUInt32LE(size, 24);
  central.writeUInt16LE(nameBytes.length, 28);
  central.writeUInt32LE(options.attrs ?? 0, 38);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(1, 8);
  end.writeUInt16LE(1, 10);
  end.writeUInt32LE(46 + nameBytes.length, 12);
  end.writeUInt32LE(30 + nameBytes.length + packed.length + descriptor.length, 16);
  return Buffer.concat([local, nameBytes, packed, descriptor, central, nameBytes, end]);
}
function combine(archives) {
  const locals = [], centrals = [];
  let offset = 0, centralSize = 0;
  for (const archive of archives) {
    const split = centralOffset(archive);
    locals.push(archive.subarray(0, split));
    const record = Buffer.from(archive.subarray(split, endOffset(archive)));
    record.writeUInt32LE(offset, 42);
    centrals.push(record);
    offset += split;
    centralSize += record.length;
  }
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(archives.length, 8);
  end.writeUInt16LE(archives.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, ...centrals, end]);
}
function withExtra(archive, extra, where) {
  const split = where === "central" ? endOffset(archive) : 30 + archive.readUInt16LE(26);
  const output = Buffer.concat([archive.subarray(0, split), extra, archive.subarray(split)]);
  if (where === "central") {
    output.writeUInt16LE(extra.length, centralOffset(archive) + 30);
    output.writeUInt32LE(archive.readUInt32LE(endOffset(archive) + 12) + extra.length, endOffset(output) + 12);
  } else {
    output.writeUInt16LE(extra.length, 28);
    output.writeUInt32LE(centralOffset(archive) + extra.length, endOffset(output) + 16);
  }
  return output;
}

test("office ZIP: stored roundtrip preserves Unicode names, binary data, and empty files", () => {
  const files = [
    { name: "skills/ทีม/SKILL.md", data: Buffer.from("# ทักษะ\n") },
    { name: "assets/binary.bin", data: Buffer.from([0, 1, 127, 128, 254, 255]) },
    { name: "workflows/empty.md", data: Buffer.alloc(0) },
    { name: "\ufeffname.md", data: Buffer.from("BOM belongs to this filename") },
  ];
  assert.deepEqual(zip.decode(zip.encode(files)), files);
  assert.deepEqual(zip.decode(zip.encode([])), []);
  assert.deepEqual(zip.decode(zip.encode([{ name: "text.md", data: "hello" }])), [{ name: "text.md", data: Buffer.from("hello") }]);
  const standardCrc = zip.encode([{ name: "crc.txt", data: "123456789" }]);
  assert.equal(standardCrc.readUInt32LE(14), 0xcbf43926);
});

